# ---- 单笔画工具 ----
def stroke(d, p, color, w):
    d.line([p[0], p[1], p[2], p[3]], fill=color, width=w)
    r = w // 2
    d.ellipse([p[0]-r, p[1]-r, p[0]+r, p[1]+r], fill=color)
    d.ellipse([p[2]-r, p[3]-r, p[2]+r, p[3]+r], fill=color)


class StrokeFont:
    """兼容 ImageFont 的最小接口：getbbox / draw"""

    def __init__(self, size):
        self.size = size
        self.s = size / 100.0

    def _box(self, x, y):
        s = self.s
        return (x * s, y * s, (x + 100) * s, (y + 100) * s)

    def getbbox(self, text, anchor="la"):
        # 返回 (x0,y0,x1,y1) 相对 (0,0)，用于居中排版
        s = self.s
        w = int(len(text) * 100 * s * 1.02)
        h = int(100 * s)
        return (0, int(8 * s), w, h)

    def draw(self, d, xy, text, fill, anchor="la"):
        s = self.s
        x, y = xy
        # anchor 支持 la(左上) —— 已由调用方算好坐标
        lw = max(1, int(round(7 * s)))
        cx = x
        for ch in text:
            segs = G.get(ch)
            if segs is None:
                # 兜底：方框 + 内部菱形（装饰性，不出现问号）
                d.rectangle([cx + 6*s, y + 8*s, cx + 94*s, y + 98*s],
                            outline=fill, width=max(1, int(3*s)))
                d.line([cx + 50*s, y + 20*s, cx + 80*s, y + 50*s,
                        cx + 50*s, y + 86*s, cx + 20*s, y + 50*s,
                        cx + 50*s, y + 20*s], fill=fill,
                       width=max(1, int(3*s)), joint="curve")
            else:
                for (x1, y1, x2, y2) in segs:
                    stroke(d, (cx + x1*s, y + y1*s, cx + x2*s, y + y2*s),
                           fill, lw)
            cx += 104 * s